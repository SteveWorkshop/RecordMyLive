package rachel.materialapps.recordmylive.ui.pages.home;

import android.app.Application;

import androidx.annotation.NonNull;
import androidx.lifecycle.AndroidViewModel;
import androidx.lifecycle.LiveData;
import androidx.lifecycle.MutableLiveData;
import androidx.lifecycle.Transformations;

import rachel.materialapps.recordmylive.logic.entity.dto.ConcertWithSongs;
import java.util.List;
import rachel.materialapps.recordmylive.logic.entity.ConcertSongEntity;

import rachel.materialapps.recordmylive.logic.entity.ConcertEntity;
import rachel.materialapps.recordmylive.logic.repository.ConcertRepository;

public class AddConcertViewModel extends AndroidViewModel {

    public static final class LinkImportState {
        public final boolean loading;
        public final rachel.materialapps.recordmylive.logic.importer.ConcertImportResult result;
        public final String error;
        LinkImportState(boolean loading,
                rachel.materialapps.recordmylive.logic.importer.ConcertImportResult result, String error) {
            this.loading = loading;
            this.result = result;
            this.error = error;
        }
    }

    private final java.util.concurrent.ExecutorService importExecutor =
            java.util.concurrent.Executors.newSingleThreadExecutor();
    private final MutableLiveData<LinkImportState> linkImportState =
            new MutableLiveData<>(new LinkImportState(false, null, null));
    private final android.os.Handler mainHandler = new android.os.Handler(android.os.Looper.getMainLooper());
    private boolean cleared;

    public LiveData<LinkImportState> getLinkImportState() { return linkImportState; }

    public void importLink(String text) {
        LinkImportState current = linkImportState.getValue();
        if (current != null && (current.loading || current.result != null)) return;
        linkImportState.setValue(new LinkImportState(true, null, null));
        importExecutor.execute(() -> {
            try {
                rachel.materialapps.recordmylive.logic.importer.ConcertLinkImportService service =
                        new rachel.materialapps.recordmylive.logic.importer.ConcertLinkImportService(
                                java.util.Arrays.asList(
                                        new rachel.materialapps.recordmylive.logic.importer.DamaiLinkParser(),
                                        new rachel.materialapps.recordmylive.logic.importer.ShowstartLinkParser()));
                rachel.materialapps.recordmylive.logic.importer.ConcertImportResult result = service.parse(text);
                try {
                    result.localCoverPath = rachel.materialapps.recordmylive.logic.importer.ImportCoverStore
                            .download(getApplication(), result.coverUrl);
                    if (result.localCoverPath == null) result.warnings.add("未取得封面，可手动添加图片");
                } catch (Exception ignored) {
                    result.warnings.add("封面下载失败，其他信息仍可导入");
                }
                mainHandler.post(() -> {
                    if (cleared) {
                        discardCover(result);
                    } else {
                        linkImportState.setValue(new LinkImportState(false, result, null));
                    }
                });
            } catch (Exception exception) {
                String message = exception instanceof IllegalArgumentException
                        || exception instanceof java.io.IOException ? exception.getMessage() : null;
                if (exception instanceof java.net.SocketTimeoutException) message = "连接超时，请检查网络后重试";
                else if (exception instanceof java.net.UnknownHostException) message = "无法连接演出平台，请检查网络后重试";
                final String error = message == null ? "链接解析失败，请稍后重试或手动填写" : message;
                mainHandler.post(() -> {
                    if (!cleared) linkImportState.setValue(new LinkImportState(false, null, error));
                });
            }
        });
    }

    public void finishLinkImport(boolean keepCover) {
        LinkImportState state = linkImportState.getValue();
        if (!keepCover && state != null) discardCover(state.result);
        linkImportState.setValue(new LinkImportState(false, null, null));
    }

    private static void discardCover(rachel.materialapps.recordmylive.logic.importer.ConcertImportResult result) {
        if (result != null && result.localCoverPath != null) {
            // The path is generated by ImportCoverStore, never supplied by the link.
            new java.io.File(result.localCoverPath).delete();
        }
    }

    @Override protected void onCleared() {
        cleared = true;
        LinkImportState state = linkImportState.getValue();
        if (state != null) discardCover(state.result);
        importExecutor.shutdownNow();
        super.onCleared();
    }

    public enum SaveState {
        IDLE, SAVING, SUCCESS, DAILY_LIMIT_REACHED, ERROR
    }

    private final MutableLiveData<SaveState> saveState =
            new MutableLiveData<>(SaveState.IDLE);
    private final ConcertRepository repository;
    private final MutableLiveData<Long> concertId = new MutableLiveData<>();
    private final LiveData<ConcertWithSongs> concertDetail;
    public AddConcertViewModel(@NonNull Application application) {
        super(application);
        repository = new ConcertRepository(application);
        concertDetail = Transformations.switchMap(
                concertId, repositoryId -> repository.getConcertDetail(repositoryId));
    }
    public LiveData<SaveState> getSaveState() {
        return saveState;
    }

    public LiveData<ConcertWithSongs> getConcertDetail() {
        return concertDetail;
    }

    public void loadConcert(long id) {
        concertId.setValue(id);
    }

    public void updateConcert(ConcertEntity concert, List<ConcertSongEntity> songs) {
        if (saveState.getValue() != SaveState.IDLE) {
            return;
        }
        saveState.setValue(SaveState.SAVING);
        repository.updateConcert(concert, songs, updated -> saveState.setValue(
                updated ? SaveState.SUCCESS : SaveState.ERROR));
    }

    public void saveConcert(ConcertEntity concert, List<ConcertSongEntity> songs) {
        if (saveState.getValue() != SaveState.IDLE) {
            return;
        }
        saveState.setValue(SaveState.SAVING);
        repository.saveConcert(concert, songs, result -> {
            switch (result) {
                case SUCCESS:
                    saveState.setValue(SaveState.SUCCESS);
                    break;
                case DAILY_LIMIT_REACHED:
                    saveState.setValue(SaveState.DAILY_LIMIT_REACHED);
                    break;
                case ERROR:
                    saveState.setValue(SaveState.ERROR);
                    break;
            }
        });
    }

    public void resetSaveState() {
        if (saveState.getValue() != SaveState.SAVING) {
            saveState.setValue(SaveState.IDLE);
        }
    }
}
